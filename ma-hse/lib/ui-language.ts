type WidenDictionary<T> = {
  [Key in keyof T]: T[Key] extends string
    ? string
    : T[Key] extends Record<string, unknown>
      ? WidenDictionary<T[Key]>
      : T[Key];
};

export type UiDictionary = WidenDictionary<(typeof UI_DICTIONARY)["en"]>;
export type DashboardUiDictionary = UiDictionary["dashboard"];
export type CompetencesUiDictionary = UiDictionary["competences"];

export function normalizeUiLocale(locale: string | null | undefined) {
  return (locale && locale in UI_DICTIONARY ? locale : "en") as keyof typeof UI_DICTIONARY;
}

function isDictionaryRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function mergeWithFallback<T>(fallback: T, selected: unknown): T {
  if (!isDictionaryRecord(fallback)) {
    return (selected ?? fallback) as T;
  }

  if (!isDictionaryRecord(selected)) {
    return fallback;
  }

  const result: Record<string, unknown> = { ...fallback };
  for (const [key, fallbackValue] of Object.entries(fallback)) {
    const selectedValue = selected[key];
    result[key] = isDictionaryRecord(fallbackValue)
      ? mergeWithFallback(fallbackValue, selectedValue)
      : selectedValue ?? fallbackValue;
  }

  return result as T;
}

export function getUiDictionary(locale: string | null | undefined): UiDictionary {
  const normalizedLocale = normalizeUiLocale(locale);
  if (normalizedLocale === "en") {
    return UI_DICTIONARY.en;
  }

  return mergeWithFallback(UI_DICTIONARY.en, UI_DICTIONARY[normalizedLocale]);
}
